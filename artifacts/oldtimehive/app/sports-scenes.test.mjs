import assert from "node:assert/strict";
import { chooseScenes, POOLS, sessionSalt, createSceneSelector } from "./sports-scenes.js";
const a = chooseScenes({ accountId: "u1", revision: 3, salt: "s" });
assert.deepEqual(a, chooseScenes({ accountId: "u1", revision: 3, salt: "s" }));
for (const k in a) assert.ok(POOLS[k].includes(a[k]));
const combos = new Set(); for (let i = 0; i < 40; i++) combos.add(JSON.stringify(chooseScenes({ accountId: "u" + i, revision: 1, salt: "s" })));
assert.ok(combos.size > 10);
let diff = 0; for (let r = 0; r < 20; r++) if (JSON.stringify(chooseScenes({ accountId: "u1", revision: r })) !== JSON.stringify(a)) diff++;
assert.ok(diff > 10);
let old = 0; for (let i = 0; i < 400; i++) if (chooseScenes({ accountId: "w" + i }).walk === "walk") old++;
assert.ok(old < 80);
const m = new Map(); const st = { getItem: k => m.get(k) ?? null, setItem: (k, v) => m.set(k, v) };
assert.equal(sessionSalt(st), sessionSalt(st)); assert.ok(sessionSalt({ getItem() { throw 1; } }));
const select = createSceneSelector(st);
const first = select({ accountId: "account-one", revision: 1 });
assert.equal(first, select({ accountId: "account-one", revision: 1 }));
const reload = createSceneSelector(st);
assert.deepEqual(reload({ accountId: "account-one", revision: 0 }), first);
const nextLogin = reload({ accountId: "account-one", revision: 2 });
for (const activity in POOLS) assert.notEqual(nextLogin[activity], first[activity]);
assert.deepEqual(createSceneSelector(st)({ accountId: "account-one", revision: 0 }), nextLogin);
const noStorage = createSceneSelector({ getItem() { throw 1; }, setItem() { throw 1; } });
assert.equal(noStorage({ accountId: "offline", revision: 1 }), noStorage({ accountId: "offline", revision: 1 }));
console.log("scenes ok");
